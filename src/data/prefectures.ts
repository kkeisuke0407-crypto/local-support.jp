export interface Prefecture {
  slug: string;
  name: string;
  kana: string;
  region: string;
  majorCities: string[];
  context: string;
  /**
   * 全国平均を1.0としたときの費用水準の目安。
   * 地域の人件費・出張費・搬出条件を反映し、相場表に「地域補正」の注記を生成する。
   * 主要（インデックス対象）都道府県のみ設定。未設定の県は補正注記を出さない。
   */
  priceFactor?: number;
  /**
   * その都道府県に固有の、業者選び・費用・作業条件に影響する事情（2〜4点）。
   * 地名置換だけの重複ページにならないよう、各ページに固有段落を生成するためのデータ。
   * 主要（インデックス対象）都道府県のみ設定。
   */
  localFactors?: { title: string; body: string }[];
}

